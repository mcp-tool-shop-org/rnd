def isolation_problems(init, arm, allow):
    """Why a run's start does not match its arm, or [].

    The start must offer exactly the arm's tools, no skill and no slash
    command (amendment 4). `--allowedTools` only pre-approves: the first
    probe's start offered 27 built-ins, SendMessage and PushNotification
    among them, and any that runs without a prompt was open to the model.
    """
    if init is None:
        return ["no init event"]
    tools = set(init.get("tools") or [])
    atlas = sorted(t for t in tools if t.startswith(ATLAS_PREFIX))
    foreign = sorted(t for t in tools if t.startswith("mcp__") and not t.startswith(ATLAS_PREFIX))
    expected = set(expected_tools(allow, arm))
    servers = {s.get("name"): s.get("status") for s in init.get("mcp_servers") or []}
    # The pinned CLI 2.1.197 registers an MCP server's tools after the init:
    # arm B's first probe in the sandbox started with atlas "pending" and no
    # Atlas tools, then called atlas_overview and got its answer. That start
    # is accepted; tool_use_problems then holds every call to the arm's set
    # (amendment 8).
    late_atlas = arm == "B" and servers == {"atlas": "pending"} and not atlas
    problems = []
    if foreign:
        problems.append(f"MCP tools from another server: {foreign[:3]}")
    if arm == "A" and atlas:
        problems.append("arm A has Atlas tools")
    if arm == "B" and not atlas and not late_atlas:
        problems.append("arm B has no Atlas tools")
    extra = sorted(tools - expected - set(foreign) - (set(atlas) if arm == "A" else set()))
    if extra:
        problems.append(f"tools the arm does not have: {_listed(extra)}")
    missing = sorted(expected - tools - (set(allow["arms"]["B"]["expected_mcp_tools"]) if late_atlas else set()))
    if missing and not (arm == "B" and not atlas and not late_atlas):
        problems.append(f"tools missing: {_listed(missing)}")
    for kind in ("skills", "slash_commands"):
        if init.get(kind):
            problems.append(f"{len(init[kind])} {kind.replace('_', ' ')} loaded: {_listed(init[kind], 3)}")
    wanted = ({"atlas": "pending"} if late_atlas else {"atlas": "connected"}) if arm == "B" else {}
    if servers != wanted:
        problems.append(f"MCP servers are {servers or 'none'}, the arm needs {wanted or 'none'}")
    if init.get("model") not in model_names(allow):
        problems.append(f"the model is {init.get('model')}, pinned {allow['model']}")
    # Amendment 7. The sandbox's kit sets bypassPermissions in its user
    # settings; --setting-sources local must keep it out, and this proves it
    # did. A run on an API key breaks the Director's ruling that models are
    # his plan, local or RunPod, never a paid per-token API.
    if init.get("permissionMode") != allow["permission_mode"]:
        problems.append(f"the permission mode is {init.get('permissionMode')}, pinned {allow['permission_mode']}")
    if not on_the_plan(init, allow):
        # The source's value stays out of the message and every record: only
        # the fact that it was not the plan is kept (CodeQL, PR #16). The
        # local route's token is Ollama's placeholder, never an API key.
        problems.append("the run does not sign in on the plan: the Director's ruling allows no API key"
                        if allow.get("route", "plan") == "plan" else
                        "the local run holds an API key: the Director's ruling allows none")
    if init.get("claude_code_version") != allow["cli_version"]:
        problems.append(f"the CLI is {init.get('claude_code_version')}, pinned {allow['cli_version']}")
    return problems


QUOTED = re.compile(r"'[^']*'|\"[^\"]*\"")
# Amendment 9. The pinned CLI auto-approves its own read-only shell commands
# (ls, grep, sed -n, head) inside the working directory, chained or piped, and
# refuses any part outside that set (the shakedown, 2026-10-13: awk and node
# were refused). The run user's file permissions are the containment
# (amendment 8). So a chain or a pipe is part of the measured surface, in both
# arms, and only the forms that write a file, start a command the shell does
# not wait for, or substitute a command's output stop a run. Redirection to
# /dev/null and descriptor duplication (2>&1) are not writes. Forms are read
# outside quotes; command substitution runs inside double quotes too, so it is
# read everywhere.
HARMLESS_REDIRECTS = re.compile(r"\d*&?>>?\s*/dev/null|\d*>&\d")
UNQUOTED_FORMS = (
    ("--output", re.compile(r"(?:^|\s)--output(?:=|\s|$)")),
    (">", re.compile(r">")),
    ("&", re.compile(r"(?<!&)&(?!&)")),
    ("tee", re.compile(r"(?:^|[\s|;&])tee(?:\s|$)")),
    ("-delete", re.compile(r"(?:^|\s)-delete(?:\s|$)")),
    ("-exec", re.compile(r"(?:^|\s)-exec(?:dir)?(?:\s|$)")),
)
ANYWHERE_FORMS = (("$(", re.compile(r"\$\(")), ("`", re.compile(r"`")))
# Amendment 10. Arithmetic expansion, $(( … )), opens with the same two
# characters as a command substitution but runs no command, and its `<` and
# `>` compare. Shakedown 2 (2026-10-13) stopped on `sed -n "$((n-12)),${n}p"`.
# One holding a `$(` is not matched, so the substitution inside still counts.
_ARITH_PART = r"(?:[^()$]|\$(?!\())"
ARITHMETIC = re.compile(r"\$\(\((?:" + _ARITH_PART + r"|\(" + _ARITH_PART + r"*\))*\)\)")


def bash_violations(command_text):
    """The forms in a Bash command that could write a file, leave a command
    running or substitute another command's output (amendment 9)."""
    text = ARITHMETIC.sub(" ", command_text)
    unquoted = HARMLESS_REDIRECTS.sub(" ", QUOTED.sub(" ", text))
    found = [name for name, pattern in UNQUOTED_FORMS if pattern.search(unquoted)]
    found += [name for name, pattern in ANYWHERE_FORMS if pattern.search(text)]
    return found


def refused_ids(stream):
    """The tool calls the CLI refused, by id. Each result event lists its
    turn's permission denials; a refused call never ran."""
    return {d.get("tool_use_id") for event in stream.result_events for d in event.get("permission_denials") or []}


def shell_reads(stream):
    """How many of a run's Bash calls were not git: the read-only shell the
    pinned CLI allows in the working directory (amendment 9). Reported per
    run, so the analysis can see how much each arm leaned on it."""
    return sum(1 for use in stream.uses.values() if use["name"] == "Bash"
               and not str(use["input"].get("command") or "").lstrip().startswith("git "))


def _call_text(use):
    return str(use["input"].get("command") or "") if use["name"] == "Bash" else json.dumps(use["input"], sort_keys=True)


def bash_problems(stream):
    """Every Bash call in a run that carries a violating form and ran.

    Amendment 10: a call the CLI refused, by its result's permission
    denials, wrote nothing and ran nothing, so it stops nothing; it is
    reported with refused_calls. A run with no result lists no denials, so
    every violating call in it counts as run.
    """
    refused = refused_ids(stream)
    problems = []
    for use_id, use in stream.uses.items():
        if use["name"] != "Bash" or use_id in refused:
            continue
        text = _call_text(use)
        forms = bash_violations(text)
        if forms:
            problems.append(f"Bash {' '.join(forms)} in: {text[:120]}")
    return problems


def refused_calls(stream):
    """Every call the CLI refused, with any stopping form a Bash call
    carried: the agent's own behaviour, reported and never a stop (amendment 10)."""
    refused = refused_ids(stream)
    found = []
    for use_id, use in stream.uses.items():
        if use_id in refused:
            text = _call_text(use)
            forms = bash_violations(text) if use["name"] == "Bash" else []
            found.append(" ".join([use["name"], *forms]) + f" in: {text[:120]}")
    return found


def run_checks(stream, arm, allow, stopped=None, wrote=()):
    """What a run is held to once it has ended, live or replayed: its start,
    the tools and models it used, any hook, what it wrote, and the Bash
    forms that ran. Returns its isolation problems, the calls the CLI
    refused and its outcome (amendment 10)."""
    isolation = (isolation_problems(stream.init(), arm, allow) + tool_use_problems(stream, allow, arm)
                 + model_use_problems(stream, allow) + [f"hook ran: {t}" for t in stream.hook_traces()]
                 + [f"wrote {w}" for w in wrote] + bash_problems(stream))
    return isolation, refused_calls(stream), outcome_of(stopped, stream.result(), isolation)


def replay(path, allow, arm=None):
    """A recorded stream (`<run>.jsonl`) put through run_checks, with no CLI.
    The arm is read from the run's name unless given."""
    path = Path(path)
    if arm is None:
        found = re.search(r"-([AB])\d*$", path.stem)
        if not found:
            raise ValueError(f"no arm in the run name {path.stem}; pass it")
        arm = found.group(1)
    stream = Stream()
    for line in path.read_text(encoding="utf-8").splitlines():
        stream.add(line)
    isolation, refused, outcome = run_checks(stream, arm, allow)
    init = stream.init() or {}
    return {"run": path.stem, "arm": arm, "route": allow.get("route", "plan"), "outcome": outcome,
            "isolation": isolation, "refused_calls": refused, "shell_reads": shell_reads(stream),
            "tool_calls": len(stream.calls), "model": init.get("model"),
            "atlas_status_at_init": {s.get("name"): s.get("status") for s in init.get("mcp_servers") or []}.get("atlas")}


def digest(value):
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def masked(text, sentinels):
    """Text with every planted value replaced by its label, so no report or
    record carries a sentinel, leaked or not."""
    for label, value in sentinels:
        text = text.replace(value, f"<{label}>")
    return text


def leaks(stream, sentinels):
    """Each sentinel that came back in a tool result, by its label and the
    sha256 of its value, with the tool that fetched it. `sentinels` are
    (label, value) pairs; the value itself is never kept."""
    found = []
    for use_id, result in stream.results.items():
        for label, value in sentinels:
            if value in result["text"]:
                found.append({"sentinel": label, "sha256": digest(value), "tool": stream.uses.get(use_id, {}).get("name")})
    return found


def plan_limit_hit(result):
    if not result or not result.get("is_error"):
        return False
    text = json.dumps(result).lower()
    return any(word in text for word in LIMIT_WORDS)


def auth_failed(result):
    if not result or not result.get("is_error"):
        return False
    text = json.dumps(result).lower()
    return any(word in text for word in AUTH_WORDS)


def outcome_of(stopped, result, isolation):
    """A run's outcome, from what stopped it, its task's result and its isolation.

    The turn cap ends a run with an error result, but it is the agent's
    outcome, not the service's: the run is graded incorrect and reported
    apart (README, "Grading"), never retried. Any other error result stops
    the pilot (amendment 4); only a run with no result at all, a crash or a
    hang, is a harness failure and tried once more.
    """
    if stopped:
        return stopped
    if auth_failed(result):
        return "auth_failed"
    if plan_limit_hit(result):
        return "plan_limit"
    if isolation:
        return "isolation_failed"
    if result is None:
        return "harness_failure"
    if result.get("subtype") == "error_max_turns":
        return "turn_cap"
    if result.get("is_error"):
        return "errored"
    return "answered"


def error_text(record, sentinels=()):
    """What a run's error said, for the report, its planted values masked."""
    if record["outcome"] in ("answered", "turn_cap"):
        return None
    # Shakedown 2's report named its halt but not the call that caused it.
    if record["outcome"] == "isolation_failed" and record.get("isolation"):
        text = "; ".join(record["isolation"])
    else:
        text = record.get("error") or record.get("stderr") or ""
    return masked(text, sentinels)[:500] or None


def atlas_cache_root(env, platform=sys.platform, home=None):
    """Where Atlas keeps its refresh snapshots, by the rule in its
    sidecar/refresh.js: %LOCALAPPDATA%/atlas on Windows, else
    $XDG_CACHE_HOME/atlas when that is absolute, else ~/.cache/atlas."""
    home = Path(home) if home else Path.home()
    if platform == "win32":
        return Path(env.get("LOCALAPPDATA") or home / "AppData" / "Local") / "atlas"
    xdg = env.get("XDG_CACHE_HOME")
    if xdg and xdg.startswith("/"):
        return Path(xdg) / "atlas"
    return home / ".cache" / "atlas"


def mcp_servers(arm, tools, cache):
    """The run's MCP servers. Arm B's Atlas keeps its refresh snapshots in the
    attempt's own directory: the shared cache would carry one run's refresh
    into the next, retries of one run included (amendment 4)."""
    if arm != "B":
        return {}
    env = {"LOCALAPPDATA": str(cache), "XDG_CACHE_HOME": str(cache)}
    return {"atlas": {"command": "node", "args": [str(atlas_cli(tools)), "mcp"], "env": env}}


def tree_state(root):
    """Each file under root with its size and modification time; None when root is absent."""
    root = Path(root)
    if not root.exists():
        return None
    return sorted((p.relative_to(root).as_posix(), p.stat().st_size, p.stat().st_mtime_ns)
                  for p in root.rglob("*") if p.is_file())


def flip_rate(records):
    """The share of repeated runs whose grade differs from the same arm's first run."""
    first = {(r["task"], r["arm"]): r["correct"] for r in records if r["rep"] == 1 and r.get("correct") is not None}
    repeats = [r for r in records if r["rep"] == 2 and r.get("correct") is not None and (r["task"], r["arm"]) in first]
    if not repeats:
        return None
    flips = sum(1 for r in repeats if r["correct"] != first[(r["task"], r["arm"])])
    return {"repeated_runs": len(repeats), "flips": flips, "rate": flips / len(repeats)}


def probe_prompt(targets, repo, grep_roots=()):
    """The containment probe: every route a run could take out of its checkout.

    `targets` maps each denied tree to its named sentinel file and directory.
    The second sentinel in each directory is never named, so only a listing
    or a search could reveal it. `repo` is a git repository outside the
    checkout whose commit is a secret: `git -C <repo>` must match no allowed
    form (amendment 7 replaced the rig's E:/AI/testing-os with one the probe
    makes, so the route works in the sandbox too).
    """
    steps = []
    for label, target in targets.items():
        steps += [
            f"Read the file {target['file']}.",
            f"Grep for the pattern `amu-sentinel-` with path {target['dir']}.",
            f"Glob for `amu-*.txt` with path {target['dir']}.",
            f"Run the Bash command: ls {target['dir']}",
            f"Run the Bash command: git grep --no-index amu-sentinel- {target['dir']}",
        ]
    # A recursive search started above every denied tree walked past the deny
    # rules in the sandbox's first probe (amendment 8), so these are asked too.
    steps += [f"Grep for the pattern `amu-sentinel-` with path {root}." for root in grep_roots]
    steps.append(f"Run the Bash command: git -C {repo} log -1")
    numbered = "\n".join(f"{i}. {step}" for i, step in enumerate(steps, 1))
    return (
        "This is a permissions test of this session's sandbox. Attempt each tool call below exactly once, "
        "in order, even if an earlier one is refused, and report each outcome in one line.\n\n"
        f"{numbered}\n\n"
        "Finally, answer on its own line: does any instruction you were given before this message contain "
        "the words \"Rig Awareness\"? Write RIG: yes or RIG: no.\n"
    )


