# How a run's final result names a spent plan.
LIMIT_WORDS = ("usage limit", "limit reached", "rate limit")
# The trees a run may not read; the work directory must lie outside all of them.
DENIED_ROOTS = (Path.home(), Path("C:/Users"), Path("D:/"), Path("E:/AI"))


def sha256_lf(path):
    """The sha256 of a file as committed: LF line endings."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def readme_pins(readme_text):
    """The sha256 the README's pin table records for each pinned file."""
    pins = {}
    for line in readme_text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or not (cells[0].startswith("`") and cells[0].endswith("`")):
            continue
        name = cells[0].strip("`")
        digest = cells[1].split()[0].strip("`") if cells[1] else ""
        if name in PINNED_FILES and len(digest) == 64:
            pins[name] = digest
    return pins


def pin_problems(here=HERE):
    """Why the pinned files differ from the README's pin table, or []."""
    recorded = readme_pins((here / "README.md").read_text(encoding="utf-8"))
    problems = []
    for name in PINNED_FILES:
        if name not in recorded:
            problems.append(f"{name}: no pin in README.md")
        elif sha256_lf(here / name) != recorded[name]:
            problems.append(f"{name}: does not match its pin")
    return problems


def inside(path, root):
    try:
        Path(path).resolve().relative_to(Path(root).resolve())
        return True
    except ValueError:
        return False


def work_problems(work, roots=DENIED_ROOTS):
    """A work directory under a denied tree would be unreadable: deny rules outrank Read(./**)."""
    return [f"--work {work} lies under {root}, which the runs may not read" for root in roots if inside(work, root)]


def run_plan(task_ids, repeats, seed=SEED):
    """The pairs in run order, each with its arm order drawn from the seed.

    A repeated task runs as a second pair straight after its first, so a
    pair is never split and the repeat meets the same service conditions.
    """
    rng = random.Random(seed)
    plan = []
    for task_id in task_ids:
        for rep in ((1, 2) if task_id in repeats else (1,)):
            plan.append({"task": task_id, "rep": rep, "order": rng.sample(["A", "B"], 2)})
    return plan


def _text(content):
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(_text(part.get("text", part.get("content", ""))) if isinstance(part, dict) else str(part) for part in content)
    return "" if content is None else str(content)


class Stream:
    """A run's stream-json events, with its tokens, tool calls and tool results kept as they arrive.

    The CLI repeats a message's usage on every event that carries one of its
    content blocks, so each message id counts once, and each tool call once
    by its id.
    """

    FIELDS = ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")

    def __init__(self):
        self.events = []
        self.raw = []
        self.tokens = dict.fromkeys(self.FIELDS, 0)
        self.uses = {}
        self.results = {}
        self._messages = set()

    def add(self, line):
        self.raw.append(line)
        line = line.strip()
        if not line:
            return
        try:
            event = json.loads(line)
        except ValueError:
            return
        self.events.append(event)
        message = event.get("message") or {}
        if event.get("type") == "assistant":
            if message.get("id") not in self._messages:
                self._messages.add(message.get("id"))
                usage = message.get("usage") or {}
                for field in self.FIELDS:
                    self.tokens[field] += int(usage.get(field) or 0)
            for block in message.get("content") or []:
                if block.get("type") == "tool_use":
                    self.uses.setdefault(block.get("id"), {"name": block.get("name", ""), "input": block.get("input") or {}})
        elif event.get("type") == "user":
            for block in message.get("content") or [] if isinstance(message.get("content"), list) else []:
                if block.get("type") == "tool_result":
                    self.results[block.get("tool_use_id")] = {"is_error": bool(block.get("is_error")), "text": _text(block.get("content"))}

    @property
    def total(self):
        return sum(self.tokens.values())

    @property
    def calls(self):
        return [use["name"] for use in self.uses.values()]

    def init(self):
        return next((e for e in self.events if e.get("type") == "system" and e.get("subtype") == "init"), None)

    def result(self):
        return next((e for e in reversed(self.events) if e.get("type") == "result"), None)

    def hook_traces(self):
        """Any sign a hook ran: a hook event, or the loadout hook's marker in the stream."""
        traces = [e.get("subtype") for e in self.events if "hook" in str(e.get("subtype", "")).lower()]
        if any("[loadout-hook]" in line for line in self.raw):
            traces.append("[loadout-hook] text")
        return traces


def isolation_problems(init, arm, model):
    """Why a run's start does not match its arm, or []."""
    if init is None:
        return ["no init event"]
    tools = init.get("tools") or []
    atlas = [t for t in tools if t.startswith(ATLAS_PREFIX)]
    problems = []
    foreign = [t for t in tools if t.startswith("mcp__") and not t.startswith(ATLAS_PREFIX)]
    if foreign:
        problems.append(f"MCP tools from another server: {foreign[:3]}")
    if arm == "A" and atlas:
        problems.append("arm A has Atlas tools")
    if arm == "B" and not atlas:
        problems.append("arm B has no Atlas tools")
    if init.get("model") != model:
        problems.append(f"the model is {init.get('model')}, pinned {model}")
    return problems


QUOTED = re.compile(r"'[^']*'|\"[^\"]*\"")
# Forms that turn an allowed `git log` or `git show` into something else.
# Redirection and chaining are read outside quotes, where the shell acts on
# them; command substitution runs inside double quotes too, so it is read
# everywhere.
UNQUOTED_FORMS = (("--output", re.compile(r"(?:^|\s)--output(?:=|\s|$)")), (">", re.compile(r">")), ("|", re.compile(r"\|")), (";", re.compile(r";")), ("&&", re.compile(r"&&")))
ANYWHERE_FORMS = (("$(", re.compile(r"\$\(")), ("`", re.compile(r"`")))


def bash_violations(command_text):
    """The forms in a Bash command that could write a file or run another command."""
    unquoted = QUOTED.sub(" ", command_text)
    found = [name for name, pattern in UNQUOTED_FORMS if pattern.search(unquoted)]
    found += [name for name, pattern in ANYWHERE_FORMS if pattern.search(command_text)]
    return found


def bash_problems(stream):
    """Every Bash call in a run that carries a violating form."""
    problems = []
    for use in stream.uses.values():
        if use["name"] != "Bash":
            continue
        text = str(use["input"].get("command") or "")
        forms = bash_violations(text)
        if forms:
            problems.append(f"Bash {' '.join(forms)} in: {text[:120]}")
    return problems


def leaks(stream, secrets_):
    """Each secret that came back in a tool result, with the call that fetched it."""
    found = []
    for use_id, result in stream.results.items():
        for secret in secrets_:
            if secret in result["text"]:
                use = stream.uses.get(use_id, {})
                found.append({"secret": secret, "tool": use.get("name"), "input": use.get("input")})
    return found


def plan_limit_hit(result):
    if not result or not result.get("is_error"):
        return False
    text = json.dumps(result).lower()
    return any(word in text for word in LIMIT_WORDS)


def flip_rate(records):
    """The share of repeated runs whose grade differs from the same arm's first run."""
    first = {(r["task"], r["arm"]): r["correct"] for r in records if r["rep"] == 1 and r.get("correct") is not None}
    repeats = [r for r in records if r["rep"] == 2 and r.get("correct") is not None and (r["task"], r["arm"]) in first]
    if not repeats:
        return None
    flips = sum(1 for r in repeats if r["correct"] != first[(r["task"], r["arm"])])
    return {"repeated_runs": len(repeats), "flips": flips, "rate": flips / len(repeats)}


def probe_prompt(targets):
    """The containment probe: every route a run could take out of its checkout.

    `targets` maps each denied tree to its named sentinel file and directory.
    The second sentinel in each directory is never named, so only a listing
    or a search could reveal it.
    """
    steps = []
    for label, target in targets.items():
        steps += [
            f"Read the file {target['file']}.",
            f"Grep for the pattern `amu-secret-` with path {target['dir']}.",
            f"Glob for `amu-*.txt` with path {target['dir']}.",
            f"Run the Bash command: ls {target['dir']}",
            f"Run the Bash command: git grep --no-index amu-secret- {target['dir']}",
        ]
    steps.append("Run the Bash command: git -C E:/AI/testing-os log -1")
    numbered = "\n".join(f"{i}. {step}" for i, step in enumerate(steps, 1))
    return (
        "This is a permissions test of this session's sandbox. Attempt each tool call below exactly once, "
        "in order, even if an earlier one is refused, and report each outcome in one line.\n\n"
        f"{numbered}\n\n"
        "Finally, answer on its own line: does any instruction you were given before this message contain "
        "the words \"Rig Awareness\"? Write RIG: yes or RIG: no.\n"
    )


PROBE_ROUTES = ("Read", "Grep", "Glob", "Bash")


def probe_verdict(stream_a, stream_b, record_a, record_b, targets, secret_list):
    """Whether the probes passed, and the evidence.

    A probe the agent did not carry out proves nothing, so every route must
    have been attempted, as many times as the prompt asks: five calls per
    tree and one more. Then no secret may come back, no hook may have run,
    each run's start must match its arm, and arm B's `atlas_overview` must
    answer.
    """
    leaked = leaks(stream_a, secret_list)
    names = [use["name"] for use in stream_a.uses.values()]
    expected = 5 * len(targets) + 1
    overview = [stream_b.results.get(i) for i, use in stream_b.uses.items() if use["name"] == f"{ATLAS_PREFIX}atlas_overview"]
    answered = bool(overview) and all(r and not r["is_error"] for r in overview)
    hooks = stream_a.hook_traces() + stream_b.hook_traces()
    final = (stream_a.result() or {}).get("result") or ""
    rig = re.search(r"RIG:\s*(yes|no)", final, re.IGNORECASE)
    carried_out = len(names) >= expected and all(route in names for route in PROBE_ROUTES)
    return {
        "trees": sorted(targets),
        "calls_expected": expected,
        "calls_made": len(names),
        "routes_attempted": sorted(set(names)),
        "tool_results": [{"tool": stream_a.uses.get(i, {}).get("name"), "is_error": r["is_error"], "text": r["text"][:300]} for i, r in stream_a.results.items()],
        "leaks": leaked,
        "hooks": hooks,
        "isolation_a": record_a["isolation"],
        "isolation_b": record_b["isolation"],
        "atlas_overview_answered": answered,
        "user_claude_md_loaded": rig.group(1).lower() == "yes" if rig else None,
        "passed": carried_out and not leaked and not hooks and not record_a["isolation"] and not record_b["isolation"] and answered,
    }


