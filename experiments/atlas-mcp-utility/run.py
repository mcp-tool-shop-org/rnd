def resolve_cli(name):
    """The CLI's executable. An npm .cmd shim cannot be started without a
    shell, so the binary it wraps is used instead."""
    found = shutil.which(name)
    if found and found.lower().endswith(".cmd"):
        binary = Path(found).parent / "node_modules" / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe"
        if binary.exists():
            return str(binary)
    return found or name


def remove_tree(path):
    """Remove a directory git wrote. Its object files are read-only on Windows."""
    def writable_then_retry(func, target, _exc):
        os.chmod(target, stat.S_IWRITE)
        func(target)
    if not Path(path).exists():
        return
    if sys.version_info >= (3, 12):
        shutil.rmtree(path, onexc=writable_then_retry)
    else:
        shutil.rmtree(path, onerror=writable_then_retry)


def git(cwd, *args, env=None):
    # The harness runs as root over checkouts the run user owns (amendment 8).
    result = subprocess.run(["git", "-c", "safe.directory=*", *args], cwd=cwd, capture_output=True, text=True, env=env)
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout


def atlas_cli(tools):
    return tools / "node_modules" / "@dogfood-lab" / "atlas" / "cli.js"


def prepare(task, work, tools):
    """The task's template checkout: the pin's history only, mapped and committed."""
    template = work / "templates" / task["id"]
    if (template / ".git").exists():
        return template
    template.mkdir(parents=True)
    git(template, "init", "--quiet")
    git(template, "fetch", "--quiet", "--no-tags", f"https://github.com/{task['repo']}.git", task["commit"])
    git(template, "-c", "advice.detachedHead=false", "checkout", "--quiet", "--detach", "FETCH_HEAD")
    mapped = subprocess.run(["node", str(atlas_cli(tools)), "map"], cwd=template, capture_output=True, text=True)
    if mapped.returncode != 0:
        raise RuntimeError(f"atlas map at {task['id']}: {mapped.stdout}{mapped.stderr}")
    git(template, "add", "-A", "atlas")
    stamp = "2026-10-13T00:00:00Z"
    env = {**os.environ, "GIT_AUTHOR_DATE": stamp, "GIT_COMMITTER_DATE": stamp}
    git(template, "-c", "user.name=atlas-mcp-utility", "-c", "user.email=atlas-mcp-utility@example.invalid",
        "commit", "--quiet", "--allow-empty", "-m", "atlas: map at the pinned engine", env=env)
    return template


def command(cli, allow, arm, mcp_config):
    # --tools sets which built-ins exist at all; the allow and deny rules
    # still gate the ones that remain (amendment 4).
    tools = list(allow["allowed_tools"]) + list(allow["arms"][arm]["extra_allowed_tools"])
    # The init event does not echo the effort, so each record takes it from
    # here (amendment 7); the permission mode is passed and then checked.
    return [
        cli, "-p",
        "--model", allow["model"],
        *(["--effort", allow["effort"]] if allow.get("effort") else []),
        "--permission-mode", allow["permission_mode"],
        "--max-turns", str(allow["max_turns"]),
        "--input-format", "stream-json",
        "--output-format", "stream-json", "--verbose",
        "--setting-sources", allow["setting_sources"],
        "--no-session-persistence",
        "--tools", ",".join(allow["builtin_tools"]),
        *(["--disable-slash-commands"] if allow["disable_slash_commands"] else []),
        "--strict-mcp-config", "--mcp-config", str(mcp_config),
        "--allowedTools", *tools,
        "--disallowedTools", *allow["disallowed_tools"],
    ]


def user_message(text):
    """One user turn as `--input-format stream-json` reads it."""
    return json.dumps({"type": "user", "message": {"role": "user", "content": [{"type": "text", "text": text}]}}) + "\n"


def chown_tree(path, uid, gid):
    """Give a file or a directory and everything under it to one owner."""
    path = Path(path)
    os.chown(path, uid, gid, follow_symlinks=False)
    if path.is_dir() and not path.is_symlink():
        for child in path.rglob("*"):
            os.chown(child, uid, gid, follow_symlinks=False)


def harness_home():
    """The harness's own home. Under sudo, HOME can still name the calling
    user's, so on POSIX it is read from the password database."""
    if os.name == "posix":
        import pwd
        return Path(pwd.getpwuid(os.geteuid()).pw_dir)
    return Path.home()


def run_env(run_as, route="plan"):
    """The CLI's whole environment: nothing of the harness's own beyond PATH,
    and on the local route Ollama's address and model (amendment 10)."""
    local = LOCAL_ENV if route == "local" else {}
    if run_as is None:
        env = {**os.environ, **CLI_ENV, **local}
        if local:
            env.pop("ANTHROPIC_API_KEY", None)
        return env
    proxy = {key: os.environ[key] for key in PROXY_ENV if key in os.environ}
    return {"HOME": run_as["home"], "USER": run_as["name"], "LOGNAME": run_as["name"],
            "PATH": os.environ.get("PATH", "/usr/bin:/bin"), "LANG": "C.UTF-8", **proxy, **CLI_ENV, **local}


def run_once(cli, run_id, arm, template, work, tools, allow, prompts, budget, run_as=None):
    """One attempt: a fresh copy of the checkout, the CLI streamed and summed as it goes.

    `prompts` are the turns, sent one at a time: each after the result event
    of the one before. The task is the first; a pilot run's second is the
    debrief (amendment 3). The session is never persisted, so a second turn
    in the same process is the only way to ask it anything afterwards.
    """
    run_dir = work / "runs" / run_id
    if run_dir.exists():
        shutil.rmtree(run_dir)
    shutil.copytree(template, run_dir)
    # Fresh for every attempt, so a retry starts as cold as the first try.
    cache = work / "runs" / f"{run_id}.cache"
    if cache.exists():
        shutil.rmtree(cache)
    cache.mkdir(parents=True)
    mcp_config = work / "runs" / f"{run_id}.mcp.json"
    mcp_config.write_text(json.dumps({"mcpServers": mcp_servers(arm, tools, cache)}), encoding="utf-8")
    if run_as is not None:
        # The run user may pass through /work/runs to its own checkout, which it
        # owns for this attempt only, and starts from an empty home (amendment 8).
        os.chmod(work / "runs", 0o711)
        reset_home(run_as["home"])
        clear_user_files(run_as["uid"])
        # The local route never signs in: no plan is in reach (amendment 10).
        if allow.get("route", "plan") == "plan":
            install_credentials(run_as["home"], run_as["credentials"], run_as["uid"], run_as["gid"])
        for path in (run_dir, cache, mcp_config):
            chown_tree(path, run_as["uid"], run_as["gid"])
    # If the override did not take, a refresh lands in the shared cache; the
    # run then fails closed rather than leave a snapshot for the next one.
    shared_cache = (atlas_cache_root({}, platform="linux", home=run_as["home"]) if run_as is not None
                    else atlas_cache_root(os.environ))
    shared_before = tree_state(shared_cache)
    stream = Stream()
    stopped = None
    started = time.time()
    # The sandbox image's own CLI updates itself; the pinned one must not
    # change under a run (amendment 7).
    argv = command(cli, allow, arm, mcp_config)
    if run_as is not None:
        argv = ["runuser", "-u", run_as["name"], "--", *argv]
    route = allow.get("route", "plan")
    proc = subprocess.Popen(argv, cwd=run_dir, stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, encoding="utf-8",
                            env=run_env(run_as, route))
    # A session that never returns a result would hold the harness forever.
    watchdog = threading.Timer(RUN_TIMEOUT_S, proc.kill)
    watchdog.start()
    pending = list(prompts)
    proc.stdin.write(user_message(pending.pop(0)))
    proc.stdin.flush()
    with (work / "runs" / f"{run_id}.jsonl").open("w", encoding="utf-8") as log:
        for line in proc.stdout:
            log.write(line)
            seen = len(stream.result_events)
            stream.add(line)
            if budget["used"] + stream.total >= budget["ceiling"]:
                proc.kill()
                stopped = "ceiling"
                break
            if len(stream.result_events) > seen:
                # A turn ended. The next goes only after a task that answered:
                # a spent plan or a failed run gets no debrief.
                last = stream.result_events[-1]
                if pending and not last.get("is_error"):
                    proc.stdin.write(user_message(pending.pop(0)))
                    proc.stdin.flush()
                else:
                    proc.stdin.close()
    proc.wait()
    timed_out = not watchdog.is_alive() and not stopped and len(stream.result_events) < len(prompts)
    watchdog.cancel()
    # A run is told not to change any file, and `git log --output=` can write one.
    wrote = [line for line in git(run_dir, "status", "--porcelain").splitlines() if line.strip()]
    if tree_state(shared_cache) != shared_before:
        wrote.append(f"into the shared Atlas cache {shared_cache.as_posix()}")
    if run_as is not None:
        # Locked again, so no later attempt can read this one (amendment 8),
        # and nothing it left in a shared temporary tree survives (amendment 9).
        for path, mode in ((run_dir, 0o700), (cache, 0o700), (mcp_config, 0o600)):
            chown_tree(path, 0, 0)
            os.chmod(path, mode)
        clear_user_files(run_as["uid"])
    result = stream.result()
    isolation, refused, outcome = run_checks(stream, arm, allow, stopped, wrote)
    record = {
        "run": run_id, "arm": arm,
        "cli_version": (stream.init() or {}).get("claude_code_version"),
        # The local route has no effort, no plan and no price; its unit is
        # wall time plus the GPU's load window, read from the host's Ollama
        # log between started_at and ended_at (amendment 10).
        "route": route,
        "effort": allow["effort"],
        "permission_mode": (stream.init() or {}).get("permissionMode"),
        "on_the_plan": on_the_plan(stream.init() or {}, allow) if route == "plan" else None,
        "started_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(started)),
        "ended_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
        # How often arm B's first turn began before Atlas's tools had
        # registered: the shakedown measures it (amendment 8).
        "atlas_status_at_init": {s.get("name"): s.get("status") for s in (stream.init() or {}).get("mcp_servers") or []}.get("atlas"),
        "exit_code": proc.returncode, "wall_ms": int((time.time() - started) * 1000), "timed_out": timed_out,
        "spent": stream.total,
        "limit_in_debrief": plan_limit_hit(stream.debrief_result()),
        "tokens": {**stream.tokens, "total": sum(stream.tokens.values())},
        "result_usage": (result or {}).get("usage"),
        "num_turns": (result or {}).get("num_turns"),
        "total_cost_usd": (result or {}).get("total_cost_usd") if route == "plan" else None,
        "tool_calls": len(stream.calls),
        "atlas_calls": sum(1 for name in stream.calls if name.startswith(ATLAS_PREFIX)),
        "shell_reads": shell_reads(stream),
        "isolation": isolation,
        "refused_calls": refused,
        "stderr": proc.stderr.read()[-2000:],
        "final_text": (result or {}).get("result"),
        "error": ("; ".join(result.get("errors") or []) or result.get("result")) if result and result.get("is_error") else None,
        # Counted against the ceiling, never in the run's figures or its grade.
        "debrief": {
            "tokens": {**stream.debrief_tokens, "total": sum(stream.debrief_tokens.values())},
            "tool_calls": stream.debrief_calls,
            "text": (stream.debrief_result() or {}).get("result"),
        } if len(prompts) > 1 else None,
        "outcome": outcome,
    }
    return record, stream


