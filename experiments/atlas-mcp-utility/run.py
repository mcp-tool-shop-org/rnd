def preflight(args):
    """The CLI, the allow-list and the problems that stop any run."""
    allow = for_route(json.loads((HERE / "allow-list.json").read_text(encoding="utf-8")), args.route)
    cli = resolve_cli(allow["cli"])
    problems = pin_problems() + work_problems(args.work)
    version = subprocess.run([cli, "--version"], capture_output=True, text=True).stdout
    if allow["cli_version"] not in version:
        problems.append(f"the CLI is {version.strip() or 'missing'}, pinned {allow['cli_version']}")
    package = atlas_cli(args.tools).parent / "package.json"
    if not package.exists() or json.loads(package.read_text(encoding="utf-8"))["version"] != allow["atlas"]["version"]:
        problems.append(f"{args.tools} does not hold Atlas {allow['atlas']['version']}")
    args.run_as_user, user_problems = run_as_checks(args)
    return cli, allow, problems + user_problems


def run_as_checks(args):
    """The run user, and why the containment of amendment 8 would not hold.

    The harness runs as root. The experiment directory (keys, this README),
    the work directory's contents and every other home must be unreadable to
    the run user, who must have no sudo and no privileged group.
    """
    if os.name != "posix":
        return None, ["the harness runs only in the sandbox, as root, with --run-as (amendment 8)"]
    import grp
    import pwd
    problems = []
    if os.geteuid() != 0:
        problems.append("the harness must run as root (amendment 8)")
    try:
        user = pwd.getpwnam(args.run_as)
    except KeyError:
        return None, problems + [f"the run user {args.run_as} does not exist"]
    groups = [g.gr_name for g in grp.getgrall() if args.run_as in g.gr_mem] + [grp.getgrgid(user.pw_gid).gr_name]
    listing = subprocess.run(["sudo", "-n", "-l", "-U", args.run_as], capture_output=True, text=True)
    problems += run_user_problems(args.run_as, groups, listing.stdout + listing.stderr)
    for label, path, traverse in (("the experiment directory", HERE, False), ("the work directory", args.work, True),
                                  ("root's home", Path("/root"), False)):
        if path.exists():
            st = path.stat()
            problems += private_problems(label, st.st_mode, st.st_uid, may_traverse=traverse)
    # Another user's home may stay theirs; it must only be closed to others.
    # The kit user's holds its account details (~/.claude.json).
    for home in sorted(Path("/home").iterdir()) if Path("/home").exists() else []:
        if home.is_dir() and home.name != args.run_as and home.stat().st_mode & 0o077:
            problems.append(f"the home {home} has mode {oct(home.stat().st_mode & 0o777)}; others may have nothing")
    # The pristine placeholder sign-in file, installed before every attempt.
    credentials = Path(args.run_as_credentials)
    if not credentials.is_file():
        problems.append(f"the run user's sign-in file {credentials} does not exist")
    else:
        st = credentials.stat()
        problems += private_problems("the run user's sign-in file", st.st_mode, st.st_uid)
    run_as = {"name": user.pw_name, "uid": user.pw_uid, "gid": user.pw_gid, "home": user.pw_dir,
              "credentials": str(credentials)}
    return run_as, problems


def probe(args, cli, allow, tasks):
    """The containment probe (arm A) and the sidecar probe (arm B)."""
    template = prepare(tasks[PROBE_TASK], args.work, args.tools)
    budget = {"used": 0, "ceiling": args.ceiling}
    # Each sentinel is a (label, value) pair. The values exist only in the
    # planted files and in memory; reports carry the label and a sha256.
    planted, targets, sentinels = [], {}, []
    secret_repo = harness_home() / f"amu-probe-repo-{os.urandom(4).hex()}"
    try:
        # "experiment" is this directory: it holds tasks.json and its keys,
        # inside the sandbox as on the rig (amendment 7).
        # Amendment 8 adds every other user's home (the kit user's holds its
        # account details) and /work/runs, where earlier runs' records live.
        runs = args.work / "runs"
        runs.mkdir(parents=True, exist_ok=True)
        others = [(f"home {h.name}", h) for h in sorted(Path("/home").iterdir())
                  if h.is_dir() and args.run_as_user and h.name != args.run_as_user["name"]] if Path("/home").exists() else []
        for label, root in (("experiment", HERE), ("home", harness_home()), *others, ("earlier runs", runs),
                            ("E:/AI", Path("E:/AI")), ("D:/", Path("D:/"))):
            if not root.exists():
                print(f"{label} is not present on this machine; not probed", file=sys.stderr)
                continue
            content = f"amu-sentinel-{os.urandom(8).hex()}"
            named = root / f"amu-probe-{os.urandom(4).hex()}.txt"
            hidden = root / f"amu-hidden-{os.urandom(8).hex()}.txt"
            for path in (named, hidden):
                path.write_text(content + "\n", encoding="utf-8")
                planted.append(path)
            targets[label] = {"file": named.as_posix(), "dir": root.as_posix()}
            sentinels += [(f"{label} content", content), (f"{label} hidden file name", hidden.name)]
        # A repository outside the checkout whose commit and message are secrets.
        secret_repo.mkdir()
        message = f"amu-commit-{os.urandom(8).hex()}"
        git(secret_repo, "init", "--quiet")
        git(secret_repo, "-c", "user.name=amu-probe", "-c", "user.email=amu-probe@example.invalid",
            "commit", "--quiet", "--allow-empty", "-m", message)
        sentinels += [("probe repository HEAD", git(secret_repo, "rev-parse", "HEAD").strip()[:12]),
                      ("probe repository message", message)]
        # The probes take one turn each: no debrief (amendment 3).
        grep_roots = ("/", args.work.as_posix(), "/home")
        record_a, stream_a = run_once(cli, "probe-A", "A", template, args.work, args.tools, allow,
                                      [probe_prompt(targets, secret_repo.as_posix(), grep_roots)], budget,
                                      run_as=args.run_as_user)
        budget["used"] += record_a["spent"]
        record_b, stream_b = run_once(cli, "probe-B", "B", template, args.work, args.tools, allow,
                                      [PROBE_B_PROMPT], budget, run_as=args.run_as_user)
        budget["used"] += record_b["spent"]
    finally:
        for path in planted:
            path.unlink(missing_ok=True)
        remove_tree(secret_repo)
    report = probe_verdict(stream_a, stream_b, record_a, record_b, targets, sentinels, grep_roots)
    report["tokens_used"] = budget["used"]
    PROBE_REPORT.parent.mkdir(parents=True, exist_ok=True)
    PROBE_REPORT.write_text(scrub(json.dumps(report, indent=1)), encoding="utf-8")
    if any(r["outcome"] == "auth_failed" for r in (record_a, record_b)):
        print(HALTING["auth_failed"], file=sys.stderr)
    print(json.dumps({"passed": report["passed"], "tokens_used": budget["used"], "leaks": len(report["leaks"]),
                      "outcomes": [r["outcome"] for r in (record_a, record_b)]}))
    return 0 if report["passed"] else 1


def results_dir(label, route):
    """Where a pilot's records go: the local route's apart (amendment 10)."""
    return HERE / "results" / (label if route == "plan" else f"{label}-{route}")


def pilot(args, cli, allow, tasks):
    probe_report = PROBE_REPORT
    out = results_dir(args.label, allow["route"])
    out.mkdir(parents=True, exist_ok=True)
    if not probe_report.exists() or not json.loads(probe_report.read_text(encoding="utf-8")).get("passed"):
        print("refusing to run the pilot: no passed probe report", file=sys.stderr)
        return 2
    spec = importlib.util.spec_from_file_location("amu_grade", HERE / "grade.py")
    grader = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(grader)
    prompt_template = (HERE / "prompt.md").read_text(encoding="utf-8")
    debrief = (HERE / "debrief.md").read_text(encoding="utf-8")
    budget = {"used": json.loads(probe_report.read_text(encoding="utf-8"))["tokens_used"], "ceiling": args.ceiling}
    plan = run_plan(PILOT, PILOT_REPEATS)
    records, dropped, attempts, failures, halted, debriefs = [], [], 0, 0, None, []
    halt_error = None
    for pair in plan:
        task = tasks[pair["task"]]
        template = prepare(task, args.work, args.tools)
        prompt = prompt_template.replace("{question}", task["question"])
        pair_records = []
        for arm in pair["order"]:
            for attempt in (1, 2):
                attempts += 1
                record, stream = run_once(cli, f"{task['id']}-{arm}{pair['rep']}", arm, template, args.work, args.tools, allow,
                                          [prompt, debrief], budget, run_as=args.run_as_user)
                record.update({"task": task["id"], "rep": pair["rep"], "attempt": attempt})
                budget["used"] += record["spent"]
                # The Bash forms that ran are in the record's isolation already
                # (run_checks); the refused calls are kept apart (amendment 10).
                if record["outcome"] == "answered":
                    graded = grader.grade(task, record["final_text"] or "")
                    record["correct"], record["grade"] = graded["correct"], graded
                elif record["outcome"] == "turn_cap":
                    record["correct"], record["grade"] = False, {"correct": False, "reason": "the turn cap, with no answer"}
                (out / f"{record['run']}-attempt{attempt}.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
                if record["outcome"] == "harness_failure":
                    failures += 1
                    continue
                break
            pair_records.append(record)
            if record.get("debrief") and record["debrief"]["text"] is not None:
                debriefs.append({"task": task["id"], "arm": arm, "rep": pair["rep"], **debrief_items(record["debrief"]["text"]),
                                 "text": record["debrief"]["text"], "tokens": record["debrief"]["tokens"]["total"],
                                 "tool_calls": record["debrief"]["tool_calls"]})
            if record["outcome"] in HALTING:
                halted = HALTING[record["outcome"]]
                halt_error = error_text(record)
            elif record.get("limit_in_debrief"):
                # The task was answered and graded; the plan ran out during
                # the debrief, so nothing more runs.
                halted = HALTING["plan_limit"]
            elif attempts >= 5 and failures / attempts > 0.2:
                halted = "more than a fifth of attempts failed in the harness"
            if halted or record["outcome"] == "harness_failure":
                break
        if len(pair_records) == 2 and all(r["outcome"] in GRADED for r in pair_records):
            records.extend(pair_records)
        else:
            dropped.append({"task": pair["task"], "rep": pair["rep"], "outcomes": [r["outcome"] for r in pair_records]})
        if halted:
            break
    report = {
        "label": args.label,
        "route": allow["route"],
        "model": allow["model"],
        # A shakedown never enters the decision and freezes no pin (amendment 8).
        "counts_toward_decision": args.label == "pilot" and allow["route"] == "plan",
        "halted": halted,
        "halt_error": halt_error,
        "known_defects_at_the_pin": list(KNOWN_DEFECTS),
        "tokens_used": budget["used"],
        "ceiling": budget["ceiling"],
        "plan": plan,
        "runs": [{k: r.get(k) for k in ("run", "task", "arm", "rep", "outcome", "correct", "tokens", "tool_calls", "atlas_calls",
                                         "num_turns", "wall_ms", "started_at", "ended_at", "total_cost_usd", "cli_version",
                                         "shell_reads", "refused_calls", *START_FIELDS)} for r in records],
        "dropped_pairs": dropped,
        "harness_failures": failures,
        "attempts": attempts,
        "flip_rate": flip_rate(records),
        # The debriefs are counted against the ceiling and reported here alone,
        # never in the runs' figures or grades (amendment 3).
        "debriefs": {"count": len(debriefs), "tokens": sum(d["tokens"] for d in debriefs),
                     "tool_calls": sum(len(d["tool_calls"]) for d in debriefs)},
    }
    (out / "report.json").write_text(scrub(json.dumps(report, indent=1)), encoding="utf-8")
    (out / "debriefs.jsonl").write_text("".join(scrub(json.dumps(d)) + "\n" for d in debriefs), encoding="utf-8")
    print(json.dumps({"label": args.label, "route": allow["route"], "halted": halted, "tokens_used": budget["used"], "runs": len(records), "dropped_pairs": len(dropped)}))
    return 1 if halted else 0


def main(argv):
    parser = argparse.ArgumentParser(description="Run the atlas-mcp-utility probes or pilot.")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--probe", action="store_true")
    mode.add_argument("--pilot", action="store_true")
    mode.add_argument("--replay", nargs="+", type=Path, metavar="STREAM",
                      help="recorded streams (<run>.jsonl) put through a run's checks with no CLI (amendment 10)")
    parser.add_argument("--work", type=Path)
    parser.add_argument("--tools", type=Path)
    parser.add_argument("--ceiling", type=int)
    parser.add_argument("--run-as",
                        help="the unprivileged user each attempt's CLI runs as; the harness itself runs as root (amendment 8)")
    parser.add_argument("--run-as-credentials", default="/root/amu-credentials.placeholder.json",
                        help="a root-only copy of the run user's placeholder sign-in file, installed before every attempt")
    parser.add_argument("--label", choices=LABELS, default="pilot",
                        help="pilot (the pre-registered run) or shakedown (amendment 8: outside the decision)")
    parser.add_argument("--route", choices=ROUTES, default="plan",
                        help="plan (Claude Code on the plan) or local (Ollama on the host, shakedown only: amendment 10)")
    args = parser.parse_args(argv)
    if args.replay:
        allow = for_route(json.loads((HERE / "allow-list.json").read_text(encoding="utf-8")), args.route)
        checked = [replay(path, allow) for path in args.replay]
        for result in checked:
            print(json.dumps(result))
        return 1 if any(r["outcome"] in HALTING for r in checked) else 0
    missing = [f"--{name.replace('_', '-')}" for name in ("work", "tools", "ceiling", "run_as") if getattr(args, name) is None]
    if missing:
        parser.error(f"--probe and --pilot need {', '.join(missing)}")
    if args.route == "local" and not (args.pilot and args.label == "shakedown"):
        parser.error("the local route runs only the shakedown: --pilot --label shakedown (amendment 10)")
    # Everything the harness writes is its own: records, streams, templates.
    os.umask(0o077)
    cli, allow, problems = preflight(args)
    if problems:
        print("refusing to run:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 2
    tasks = {t["id"]: t for t in json.loads((HERE / "tasks.json").read_text(encoding="utf-8"))}
    RESULTS.mkdir(parents=True, exist_ok=True)
    return probe(args, cli, allow, tasks) if args.probe else pilot(args, cli, allow, tasks)


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
