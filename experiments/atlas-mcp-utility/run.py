# (the per-attempt records hold them already): amendments 7 and 8.
START_FIELDS = ("route", "effort", "permission_mode", "on_the_plan", "atlas_status_at_init")
PROBE_B_PROMPT = "Call the atlas_overview tool once, then name this repository's parts in one line.\n"


DEBRIEF_ITEMS = ("time_and_cost", "clarity", "tools", "confidence", "future_development", "other")
ITEM_START = re.compile(r"^\s*(?:\*\*)?([1-6])[.)]", re.MULTILINE)


def debrief_items(text):
    """Each numbered answer of a debrief as its own field, or None where the
    answer has no such item. Item 4, confidence, is a self-report and no metric."""
    items = dict.fromkeys(DEBRIEF_ITEMS)
    if not text:
        return items
    starts = [(int(m.group(1)), m.start(), m.end()) for m in ITEM_START.finditer(text)]
    for i, (number, _, end) in enumerate(starts):
        stop = starts[i + 1][1] if i + 1 < len(starts) else len(text)
        key = DEBRIEF_ITEMS[number - 1]
        if items[key] is None:
            items[key] = text[end:stop].strip().lstrip("*").strip()
    return items


def scrub(text):
    """Text for a public results file: the operator's home path says which
    tree, not where it is. The identity scan still gates the commit."""
    home = Path.home()
    for spelling in {home.as_posix(), str(home), str(home).replace("\\", "\\\\")}:
        text = text.replace(spelling, "~")
    return text


def probe_verdict(stream_a, stream_b, record_a, record_b, targets, sentinels, grep_roots=()):
    """Whether the probes passed, and the evidence.

    A probe the agent did not carry out proves nothing, so every route must
    have been attempted, as many times as the prompt asks: five calls per
    tree and one more. Then no sentinel may come back, no hook may have run,
    each run's start must match its arm, both runs must end in an answer,
    and arm B's `atlas_overview` must return a result that is no error: with
    `--tools` there is no ToolSearch, so that call proves the Atlas tools are
    callable as they start (amendment 4). Each run's outcome and any error it
    ended in are reported, so a failed probe says why.
    """
    leaked = leaks(stream_a, sentinels)
    names = [use["name"] for use in stream_a.uses.values()]
    expected = 5 * len(targets) + len(grep_roots) + 1
    overview = [stream_b.results.get(i) for i, use in stream_b.uses.items() if use["name"] == f"{ATLAS_PREFIX}atlas_overview"]
    answered = bool(overview) and all(r and not r["is_error"] for r in overview)
    hooks = stream_a.hook_traces() + stream_b.hook_traces()
    final = (stream_a.result() or {}).get("result") or ""
    rig = re.search(r"RIG:\s*(yes|no)", final, re.IGNORECASE)
    carried_out = len(names) >= expected and all(route in names for route in PROBE_ROUTES)
    return {
        "trees": sorted(targets),
        "grep_roots": list(grep_roots),
        "calls_expected": expected,
        "calls_made": len(names),
        "routes_attempted": sorted(set(names)),
        "tool_results": [{"tool": stream_a.uses.get(i, {}).get("name"), "is_error": r["is_error"], "text": masked(r["text"], sentinels)[:300]} for i, r in stream_a.results.items()],
        "sentinels": [{"label": label, "sha256": digest(value)} for label, value in sentinels],
        "leaks": leaked,
        "hooks": hooks,
        "isolation_a": record_a["isolation"],
        "isolation_b": record_b["isolation"],
        "records": [{"run": r.get("run"), "outcome": r.get("outcome"), "exit_code": r.get("exit_code"),
                     "cli_version": r.get("cli_version"), "error": error_text(r, sentinels),
                     **{k: r.get(k) for k in START_FIELDS}} for r in (record_a, record_b)],
        "atlas_overview_answered": answered,
        "user_claude_md_loaded": rig.group(1).lower() == "yes" if rig else None,
        "passed": (carried_out and not leaked and not hooks and not record_a["isolation"] and not record_b["isolation"]
                   and answered and record_a.get("outcome") == "answered" and record_b.get("outcome") == "answered"),
    }


