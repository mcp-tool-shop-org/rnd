"""Run the atlas-mcp-utility pilot as pre-registered (README.md, amendment 2).

Refuses to start unless every pinned file matches the README's pin table,
the CLI is the pinned version and the tools directory holds the pinned
Atlas. Prepares one checkout per task: the pin's history and no later, the
map regenerated by the pinned engine and committed. Copies it fresh for
every run and runs Claude Code in print mode in it, arm A with no MCP
server and arm B with the Atlas sidecar, the prompt on stdin. Sums each
run's tokens from its own usage records as it streams, and stops at the
ceiling, at a plan usage limit, at a run whose start does not match its
arm, or when more than a fifth of attempts fail in the harness. A run that
fails in the harness is tried once more; failing again drops its pair.
Grades with grade.py, and writes one record per attempt and a report.

Only the pilot has the Director's go. Standard library only. Usage:
  python run.py --pilot --work <dir> --tools <dir> --ceiling 30000000
"""
import argparse
import hashlib
import importlib.util
import json
import os
import random
import shutil
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
PINNED_FILES = ("tasks.json", "prompt.md", "allow-list.json", "grade.py")
SEED = 20261013
PILOT = ("RC03", "CF09", "CF02", "CF04")
PILOT_REPEATS = ("RC03", "CF04")
ATLAS_PREFIX = "mcp__atlas__"
# How a run's final result names a spent plan.
LIMIT_WORDS = ("usage limit", "limit reached", "rate limit")


def sha256_lf(path):
    """The sha256 of a file as committed: LF line endings."""
    return hashlib.sha256(path.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def readme_pins(readme_text):
    """The sha256 the README's pin table records for each pinned file."""
    pins = {}
    for line in readme_text.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 2 or not (cells[0].startswith("`") and cells[0].endswith("`")):
            continue
        name = cells[0].strip("`")
        digest = cells[1].split()[0].strip("`") if cells[1] else ""
        if name in PINNED_FILES and len(digest) == 64:
            pins[name] = digest
    return pins


def pin_problems(here=HERE):
    """Why the pinned files differ from the README's pin table, or []."""
    recorded = readme_pins((here / "README.md").read_text(encoding="utf-8"))
    problems = []
    for name in PINNED_FILES:
        if name not in recorded:
            problems.append(f"{name}: no pin in README.md")
        elif sha256_lf(here / name) != recorded[name]:
            problems.append(f"{name}: does not match its pin")
    return problems


def run_plan(task_ids, repeats, seed=SEED):
    """The pairs in run order, each with its arm order drawn from the seed.

    A repeated task runs as a second pair straight after its first, so a
    pair is never split and the repeat meets the same service conditions.
    """
    rng = random.Random(seed)
    plan = []
    for task_id in task_ids:
        for rep in ((1, 2) if task_id in repeats else (1,)):
            plan.append({"task": task_id, "rep": rep, "order": rng.sample(["A", "B"], 2)})
    return plan


class Stream:
    """A run's stream-json events, with its tokens and tool calls kept as they arrive.

    The CLI repeats a message's usage on every event that carries one of its
    content blocks, so each message id counts once, and each tool call once
    by its id.
    """

    FIELDS = ("input_tokens", "cache_creation_input_tokens", "cache_read_input_tokens", "output_tokens")

    def __init__(self):
        self.events = []
        self.tokens = dict.fromkeys(self.FIELDS, 0)
        self._messages = set()
        self._calls = {}

    def add(self, line):
        line = line.strip()
        if not line:
            return
        try:
            event = json.loads(line)
        except ValueError:
            return
        self.events.append(event)
        if event.get("type") != "assistant":
            return
        message = event.get("message") or {}
        if message.get("id") not in self._messages:
            self._messages.add(message.get("id"))
            usage = message.get("usage") or {}
            for field in self.FIELDS:
                self.tokens[field] += int(usage.get(field) or 0)
        for block in message.get("content") or []:
            if block.get("type") == "tool_use":
                self._calls.setdefault(block.get("id"), block.get("name", ""))

    @property
    def total(self):
        return sum(self.tokens.values())

    @property
    def calls(self):
        return list(self._calls.values())

    def init(self):
        return next((e for e in self.events if e.get("type") == "system" and e.get("subtype") == "init"), None)

    def result(self):
        return next((e for e in reversed(self.events) if e.get("type") == "result"), None)


def isolation_problems(init, arm, model):
    """Why a run's start does not match its arm, or []."""
    if init is None:
        return ["no init event"]
    tools = init.get("tools") or []
    atlas = [t for t in tools if t.startswith(ATLAS_PREFIX)]
    problems = []
    foreign = [t for t in tools if t.startswith("mcp__") and not t.startswith(ATLAS_PREFIX)]
    if foreign:
        problems.append(f"MCP tools from another server: {foreign[:3]}")
    if arm == "A" and atlas:
        problems.append("arm A has Atlas tools")
    if arm == "B" and not atlas:
        problems.append("arm B has no Atlas tools")
    if init.get("model") != model:
        problems.append(f"the model is {init.get('model')}, pinned {model}")
    return problems


def plan_limit_hit(result):
    if not result or not result.get("is_error"):
        return False
    text = json.dumps(result).lower()
    return any(word in text for word in LIMIT_WORDS)


def flip_rate(records):
    """The share of repeated runs whose grade differs from the same arm's first run."""
    first = {(r["task"], r["arm"]): r["correct"] for r in records if r["rep"] == 1 and r.get("correct") is not None}
    repeats = [r for r in records if r["rep"] == 2 and r.get("correct") is not None and (r["task"], r["arm"]) in first]
    if not repeats:
        return None
    flips = sum(1 for r in repeats if r["correct"] != first[(r["task"], r["arm"])])
    return {"repeated_runs": len(repeats), "flips": flips, "rate": flips / len(repeats)}


# ---- below here the harness touches git, the CLI and the network -----------


def resolve_cli(name):
    """The CLI's executable. An npm .cmd shim cannot be started without a
    shell, so the binary it wraps is used instead."""
    found = shutil.which(name)
    if found and found.lower().endswith(".cmd"):
        binary = Path(found).parent / "node_modules" / "@anthropic-ai" / "claude-code" / "bin" / "claude.exe"
        if binary.exists():
            return str(binary)
    return found or name


def git(cwd, *args, env=None):
    result = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True, env=env)
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)}: {result.stderr.strip()}")
    return result.stdout


def atlas_cli(tools):
    return tools / "node_modules" / "@dogfood-lab" / "atlas" / "cli.js"


def prepare(task, work, tools):
    """The task's template checkout: the pin's history only, mapped and committed."""
    template = work / "templates" / task["id"]
    if (template / ".git").exists():
        return template
    template.mkdir(parents=True)
    git(template, "init", "--quiet")
    git(template, "fetch", "--quiet", "--no-tags", f"https://github.com/{task['repo']}.git", task["commit"])
    git(template, "-c", "advice.detachedHead=false", "checkout", "--quiet", "--detach", "FETCH_HEAD")
    mapped = subprocess.run(["node", str(atlas_cli(tools)), "map"], cwd=template, capture_output=True, text=True)
    if mapped.returncode != 0:
        raise RuntimeError(f"atlas map at {task['id']}: {mapped.stdout}{mapped.stderr}")
    git(template, "add", "-A", "atlas")
    stamp = "2026-10-13T00:00:00Z"
    env = {**os.environ, "GIT_AUTHOR_DATE": stamp, "GIT_COMMITTER_DATE": stamp}
    git(template, "-c", "user.name=atlas-mcp-utility", "-c", "user.email=atlas-mcp-utility@example.invalid",
        "commit", "--quiet", "--allow-empty", "-m", "atlas: map at the pinned engine", env=env)
    return template


def command(cli, allow, arm, mcp_config):
    tools = list(allow["allowed_tools"]) + list(allow["arms"][arm]["extra_allowed_tools"])
    return [
        cli, "-p",
        "--model", allow["model"],
        "--max-turns", str(allow["max_turns"]),
        "--output-format", "stream-json", "--verbose",
        "--setting-sources", allow["setting_sources"],
        "--no-session-persistence",
        "--strict-mcp-config", "--mcp-config", str(mcp_config),
        "--allowedTools", *tools,
        "--disallowedTools", *allow["disallowed_tools"],
    ]


def run_once(cli, task, arm, rep, template, work, tools, allow, prompt, budget):
    """One attempt: a fresh copy of the checkout, the CLI streamed and summed as it goes."""
    run_id = f"{task['id']}-{arm}{rep}"
    run_dir = work / "runs" / run_id
    if run_dir.exists():
        shutil.rmtree(run_dir)
    shutil.copytree(template, run_dir)
    servers = {"atlas": {"command": "node", "args": [str(atlas_cli(tools)), "mcp"]}} if arm == "B" else {}
    mcp_config = work / "runs" / f"{run_id}.mcp.json"
    mcp_config.write_text(json.dumps({"mcpServers": servers}), encoding="utf-8")
    stream = Stream()
    stopped = None
    started = time.time()
    proc = subprocess.Popen(command(cli, allow, arm, mcp_config), cwd=run_dir, stdin=subprocess.PIPE,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, encoding="utf-8")
    proc.stdin.write(prompt)
    proc.stdin.close()
    with (work / "runs" / f"{run_id}.jsonl").open("w", encoding="utf-8") as log:
        for line in proc.stdout:
            log.write(line)
            stream.add(line)
            if budget["used"] + stream.total >= budget["ceiling"]:
                proc.kill()
                stopped = "ceiling"
                break
    proc.wait()
    result = stream.result()
    record = {
        "run": run_id, "task": task["id"], "arm": arm, "rep": rep,
        "exit_code": proc.returncode, "wall_ms": int((time.time() - started) * 1000),
        "tokens": {**stream.tokens, "total": stream.total},
        "result_usage": (result or {}).get("usage"),
        "num_turns": (result or {}).get("num_turns"),
        "total_cost_usd": (result or {}).get("total_cost_usd"),
        "tool_calls": len(stream.calls),
        "atlas_calls": sum(1 for name in stream.calls if name.startswith(ATLAS_PREFIX)),
        "isolation": isolation_problems(stream.init(), arm, allow["model"]),
        "stderr": proc.stderr.read()[-2000:],
        "final_text": (result or {}).get("result"),
    }
    if stopped:
        record["outcome"] = "ceiling"
    elif plan_limit_hit(result):
        record["outcome"] = "plan_limit"
    elif record["isolation"]:
        record["outcome"] = "isolation_failed"
    elif result is None or result.get("is_error"):
        record["outcome"] = "harness_failure"
    else:
        record["outcome"] = "answered"
    return record


HALTING = {"ceiling": "the token ceiling", "plan_limit": "the plan usage limit", "isolation_failed": "a run whose start did not match its arm"}


def main(argv):
    parser = argparse.ArgumentParser(description="Run the atlas-mcp-utility pilot.")
    parser.add_argument("--pilot", action="store_true")
    parser.add_argument("--work", required=True, type=Path)
    parser.add_argument("--tools", required=True, type=Path)
    parser.add_argument("--ceiling", required=True, type=int)
    args = parser.parse_args(argv)
    if not args.pilot:
        print("only the pilot has the Director's go: run with --pilot", file=sys.stderr)
        return 2
    allow = json.loads((HERE / "allow-list.json").read_text(encoding="utf-8"))
    cli = resolve_cli(allow["cli"])
    problems = pin_problems()
    version = subprocess.run([cli, "--version"], capture_output=True, text=True).stdout
    if allow["cli_version"] not in version:
        problems.append(f"the CLI is {version.strip() or 'missing'}, pinned {allow['cli_version']}")
    package = atlas_cli(args.tools).parent / "package.json"
    if not package.exists() or json.loads(package.read_text(encoding="utf-8"))["version"] != allow["atlas"]["version"]:
        problems.append(f"{args.tools} does not hold Atlas {allow['atlas']['version']}")
    if problems:
        print("refusing to run:\n  " + "\n  ".join(problems), file=sys.stderr)
        return 2
    spec = importlib.util.spec_from_file_location("amu_grade", HERE / "grade.py")
    grader = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(grader)
    tasks = {t["id"]: t for t in json.loads((HERE / "tasks.json").read_text(encoding="utf-8"))}
    prompt_template = (HERE / "prompt.md").read_text(encoding="utf-8")
    out = HERE / "results" / "pilot"
    out.mkdir(parents=True, exist_ok=True)
    budget = {"used": 0, "ceiling": args.ceiling}
    plan = run_plan(PILOT, PILOT_REPEATS)
    records, dropped, attempts, failures, halted = [], [], 0, 0, None
    for pair in plan:
        task = tasks[pair["task"]]
        template = prepare(task, args.work, args.tools)
        prompt = prompt_template.replace("{question}", task["question"])
        pair_records = []
        for arm in pair["order"]:
            for attempt in (1, 2):
                attempts += 1
                record = run_once(cli, task, arm, pair["rep"], template, args.work, args.tools, allow, prompt, budget)
                record["attempt"] = attempt
                budget["used"] += record["tokens"]["total"]
                if record["outcome"] == "answered":
                    graded = grader.grade(task, record["final_text"] or "")
                    record["correct"], record["grade"] = graded["correct"], graded
                (out / f"{record['run']}-attempt{attempt}.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
                if record["outcome"] == "harness_failure":
                    failures += 1
                    continue
                break
            pair_records.append(record)
            if record["outcome"] in HALTING:
                halted = HALTING[record["outcome"]]
            elif attempts >= 5 and failures / attempts > 0.2:
                halted = "more than a fifth of attempts failed in the harness"
            if halted or record["outcome"] == "harness_failure":
                break
        if all(r["outcome"] == "answered" for r in pair_records) and len(pair_records) == 2:
            records.extend(pair_records)
        else:
            dropped.append({"task": pair["task"], "rep": pair["rep"], "outcomes": [r["outcome"] for r in pair_records]})
        if halted:
            break
    report = {
        "halted": halted,
        "tokens_used": budget["used"],
        "ceiling": budget["ceiling"],
        "plan": plan,
        "runs": [{k: r.get(k) for k in ("run", "task", "arm", "rep", "correct", "tokens", "tool_calls", "atlas_calls", "num_turns", "wall_ms", "total_cost_usd")} for r in records],
        "dropped_pairs": dropped,
        "harness_failures": failures,
        "attempts": attempts,
        "flip_rate": flip_rate(records),
    }
    (out / "report.json").write_text(json.dumps(report, indent=1), encoding="utf-8")
    print(json.dumps({"halted": halted, "tokens_used": budget["used"], "runs": len(records), "dropped_pairs": len(dropped)}))
    return 1 if halted else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
