"""Run the atlas-mcp-utility probes and pilot as pre-registered (README.md, amendment 2).

Refuses to start unless every pinned file matches the README's pin table,
the CLI is the pinned version, the tools directory holds the pinned Atlas,
and the work directory lies outside every tree the runs may not read.
Prepares one checkout per task: the pin's history and no later, the map
regenerated by the pinned engine and committed. Copies it fresh for every
run and runs Claude Code in print mode in it, arm A with no MCP server and
arm B with the Atlas sidecar, the prompt on stdin.

`--probe` proves the isolation before any graded run. It plants sentinel
files holding random tokens in each denied tree, asks arm A to reach them by
every route the runs could take, and passes only if no token ever comes back
and no hook ran; it asks arm B for `atlas_overview`, which must answer. The
sentinels are removed afterwards.

`--pilot` runs the pre-registered pairs. It sums each run's tokens from its
own usage records as it streams, and stops at the ceiling (counting the
probes' tokens), at a plan usage limit, at a run whose start does not match
its arm or that wrote into its checkout, or when more than a fifth of
attempts fail in the harness. A run that fails in the harness is tried once
more; failing again drops its pair. It grades with grade.py and writes one
record per attempt and a report. Only the pilot has the Director's go.

Standard library only. Usage:
  python run.py --probe --work <dir> --tools <dir> --ceiling 30000000
  python run.py --pilot --work <dir> --tools <dir> --ceiling 30000000
"""
